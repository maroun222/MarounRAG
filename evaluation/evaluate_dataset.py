# ============================================================
# 3. Load the RAG models once
# ============================================================

print("\nLoading embedding model...")

embedding_model = HuggingFaceEmbeddings(
    model_name="BAAI/bge-small-en-v1.5",
    model_kwargs={
        "device": "cpu",
        "local_files_only": True,
    },
    encode_kwargs={
        "normalize_embeddings": True,
    },
)


print("Loading reranking model...")

reranker = CrossEncoder(
    "cross-encoder/ms-marco-MiniLM-L4-v2",
    device="cpu",
    local_files_only=True,
)


# Qwen is used only as the DeepEval judge
judge_model = OllamaModel(
    model="qwen2.5:1.5b",
    base_url="http://localhost:11434",
    temperature=0,
)


# ============================================================
# 4. Function that runs one question through the RAG pipeline
# ============================================================

def run_rag(question: str, collection) -> dict:
    """
    Run one question through retrieval, reranking,
    passage selection, and answer generation.

    Returns:
        answer:
            The answer generated by Llama.

        retrieval_context:
            The ranked passages used by DeepEval.

        selected_page:
            The page of the best passage.

        best_context:
            The exact passage sent to Llama.
    """

    # --------------------------------------------------------
    # A. Embed the question
    # --------------------------------------------------------

    query_vector = embedding_model.embed_query(question)


    # --------------------------------------------------------
    # B. Retrieve 10 candidate chunks from Weaviate
    # --------------------------------------------------------

    results = collection.query.near_vector(
        near_vector=query_vector,
        target_vector="default",
        limit=10,
        return_properties=[
            "text",
            "page_number",
        ],
        return_metadata=MetadataQuery(distance=True),
    )

    if not results.objects:
        raise RuntimeError(
            f"No Weaviate results found for question: {question}"
        )


    retrieved_chunks = []

    for result in results.objects:
        text = result.properties.get("text", "")
        page = int(
            result.properties.get("page_number", 0)
        )

        if text.strip():
            retrieved_chunks.append(
                {
                    "text": text,
                    "page": page,
                }
            )


    # --------------------------------------------------------
    # C. Rerank the retrieved chunks
    # --------------------------------------------------------

    chunk_pairs = [
        [question, chunk["text"]]
        for chunk in retrieved_chunks
    ]

    chunk_scores = reranker.predict(chunk_pairs)

    ranked_chunks = list(
        zip(retrieved_chunks, chunk_scores)
    )

    ranked_chunks.sort(
        key=lambda item: float(item[1]),
        reverse=True,
    )


    # --------------------------------------------------------
    # D. Create smaller heading-description passages
    # --------------------------------------------------------

    passages_by_text = {}

    for chunk, chunk_score in ranked_chunks[:5]:
        page = chunk["page"]
        text = chunk["text"]

        blocks = [
            " ".join(block.split())
            for block in text.split("\n\n")
            if block.strip()
        ]

        current_heading = None

        for block in blocks:
            words = re.findall(
                r"[A-Za-z]+",
                block,
            )

            # Save meaningful short headings
            if len(block) < 150 and len(words) >= 3:
                current_heading = block
                continue

            # Ignore short OCR noise
            if len(block) < 60:
                continue

            if current_heading:
                passage_text = (
                    current_heading
                    + "\n"
                    + block
                )
            else:
                passage_text = block

            key = passage_text.lower()

            # Remove duplicate passages
            if (
                key not in passages_by_text
                or page < passages_by_text[key]["page"]
            ):
                passages_by_text[key] = {
                    "text": passage_text,
                    "page": page,
                }

            current_heading = None


    passages = list(passages_by_text.values())


    # Fallback if passage splitting found nothing useful
    if not passages:
        passages = [
            {
                "text": chunk["text"],
                "page": chunk["page"],
            }
            for chunk, score in ranked_chunks[:5]
        ]


    # --------------------------------------------------------
    # E. Rerank the smaller passages
    # --------------------------------------------------------

    passage_pairs = [
        [question, passage["text"]]
        for passage in passages
    ]

    passage_scores = reranker.predict(
        passage_pairs
    )


    stop_words = {
        "how",
        "should",
        "the",
        "a",
        "an",
        "for",
        "to",
        "of",
        "is",
        "are",
        "be",
        "with",
        "and",
        "often",
        "frequently",
    }


    question_words = {
        word.lower()
        for word in re.findall(
            r"[A-Za-z]+",
            question,
        )
        if word.lower() not in stop_words
    }


    combined_scores = []

    for index, passage in enumerate(passages):
        heading = passage["text"].split(
            "\n",
            1,
        )[0]

        heading_words = {
            word.lower()
            for word in re.findall(
                r"[A-Za-z]+",
                heading,
            )
        }

        semantic_score = float(
            passage_scores[index]
        )

        # Words found in the full passage
        passage_words = {
            word.lower()
            for word in re.findall(
                r"[A-Za-z]+",
                passage["text"],
            )
        }

# Important words matching the heading
        heading_matches = len(
            question_words & heading_words
        )

# Important words matching anywhere in the passage
        passage_matches = len(
            question_words & passage_words
        )

        combined_score = (
            semantic_score
            + 2.0 * heading_matches
            + 0.25 * passage_matches
        )


        # Prevent active/passive discovery confusion
        if (
            "active" in question_words
            and "passive" in heading_words
        ):
            combined_score -= 5

        if (
            "passive" in question_words
            and "active" in heading_words
        ):
            combined_score -= 5

        combined_scores.append(
            combined_score
        )


    # Sort passages from best to worst
    ranked_passage_indices = sorted(
        range(len(passages)),
        key=lambda index: combined_scores[index],
        reverse=True,
    )


    ranked_passages = [
        passages[index]
        for index in ranked_passage_indices
    ]


    best_passage = ranked_passages[0]
    best_text = best_passage["text"]
    best_page = best_passage["page"]


    # Contextual Precision needs the passages in ranked order
    retrieval_context = [
        f"Page {passage['page']}\n{passage['text']}"
        for passage in ranked_passages[:3]
    ]


    # The exact context sent to the generation model
    best_context = (
        f"Page {best_page}\n{best_text}"
    )


    # --------------------------------------------------------
    # F. Generate the final answer using Llama
    # --------------------------------------------------------

    system_message = """
You are an extractive question-answering assistant.

Answer using only the supplied passage.

Rules:
- Identify the exact actions and frequencies written in the passage.
- Preserve exact frequencies, intervals, and action options.
- Do not add information from other topics.
- Give a short and direct answer.
- Mention the supplied page number.
- If the passage does not answer the question, say that the context is insufficient.
"""


    user_message = f"""
Question:
{question}

Passage from page {best_page}:
{best_text}

Write the answer in one or two sentences.
"""


    response = chat(
        model="llama3.2:1b-instruct-q4_K_M",
        messages=[
            {
                "role": "system",
                "content": system_message,
            },
            {
                "role": "user",
                "content": user_message,
            },
        ],
        options={
            "temperature": 0.0,
            "num_ctx": 1024,
            "num_predict": 120,
        },
    )


    answer = response.message.content.strip()


    return {
        "answer": answer,
        "retrieval_context": retrieval_context,
        "selected_page": best_page,
        "best_context": best_context,
    }


# ============================================================
# 5. Run every golden question through the real RAG system
# ============================================================

test_cases = []
saved_outputs = []

correct_page_count = 0

client = weaviate.connect_to_local()
collection = client.collections.use(
    "CISControls"
)


try:
    for case_number, case in enumerate(
        golden_data,
        start=1,
    ):
        question = case["question"]
        expected_answer = case["expected_answer"]
        expected_page = int(case["expected_page"])
        expected_safeguard = case[
            "expected_safeguard"
        ]


        print("\n" + "=" * 80)
        print(
            f"Running evaluation case "
            f"{case_number}/{len(golden_data)}"
        )
        print("Question:", question)


        rag_result = run_rag(
            question=question,
            collection=collection,
        )


        generated_answer = rag_result["answer"]
        selected_page = rag_result["selected_page"]
        retrieval_context = rag_result[
            "retrieval_context"
        ]
        best_context = rag_result["best_context"]


        page_correct = (
            selected_page == expected_page
        )

        if page_correct:
            correct_page_count += 1


        print("Expected page:", expected_page)
        print("Selected page:", selected_page)
        print("Page correct:", page_correct)
        print("Generated answer:", generated_answer)


        # Create one DeepEval test case
        test_case = LLMTestCase(
            input=question,
            actual_output=generated_answer,
            expected_output=expected_answer,

            # Ranked passages returned by the retriever/reranker
            retrieval_context=retrieval_context,

            # Exact passage sent to Llama
            context=[best_context],
        )

        test_cases.append(test_case)


        # Save a readable copy of the RAG output
        saved_outputs.append(
            {
                "id": case["id"],
                "question": question,
                "actual_answer": generated_answer,
                "expected_answer": expected_answer,
                "expected_page": expected_page,
                "selected_page": selected_page,
                "page_correct": page_correct,
                "expected_safeguard": expected_safeguard,
                "retrieval_context": retrieval_context,
            }
        )


finally:
    client.close()


# ============================================================
# 6. Save the generated RAG outputs
# ============================================================

with open(
    rag_outputs_path,
    "w",
    encoding="utf-8",
) as file:
    json.dump(
        saved_outputs,
        file,
        indent=2,
        ensure_ascii=False,
    )


page_accuracy = (
    correct_page_count
    / len(golden_data)
)

print("\n" + "=" * 80)
print(
    "Correct selected pages:",
    f"{correct_page_count}/{len(golden_data)}",
)
print(
    "Page-selection accuracy:",
    f"{page_accuracy:.2%}",
)
print(
    "RAG outputs saved to:",
    rag_outputs_path,
)


# ============================================================
# 7. Create the six DeepEval metrics
# ============================================================

faithfulness = FaithfulnessMetric(
    threshold=0.5,
    model=judge_model,
    include_reason=True,
    async_mode=False,
)


answer_relevancy = AnswerRelevancyMetric(
    threshold=0.5,
    model=judge_model,
    include_reason=True,
    async_mode=False,
)


contextual_precision = ContextualPrecisionMetric(
    threshold=0.5,
    model=judge_model,
    include_reason=True,
    async_mode=False,
)


contextual_recall = ContextualRecallMetric(
    threshold=0.5,
    model=judge_model,
    include_reason=True,
    async_mode=False,
)


contextual_relevancy = ContextualRelevancyMetric(
    threshold=0.5,
    model=judge_model,
    include_reason=True,
    async_mode=False,
)


hallucination = HallucinationMetric(
    threshold=0.5,
    model=judge_model,
    include_reason=True,
    async_mode=False,
)


# ============================================================
# 8. Evaluate all test cases
# ============================================================

print("\nStarting DeepEval evaluation...")
print("This may take several minutes on CPU.")
print("Number of DeepEval test cases:", len(test_cases))

evaluate(
    test_cases=test_cases,
    metrics=[
        faithfulness,
        answer_relevancy,
        contextual_precision,
        contextual_recall,
        contextual_relevancy,
        hallucination,
    ],

    # Run sequentially to reduce memory usage
    async_config=AsyncConfig(
        run_async=False,
    ),

    # Do not stop the full run if the small judge
    # returns an invalid response for one metric
    error_config=ErrorConfig(
        ignore_errors=True,
    ),

    # Save detailed results locally
    display_config=DisplayConfig(
        results_folder=str(results_folder),
    ),

    # Removes the "No hyperparameters logged" warning
    hyperparameters={
        "generator_model": (
            "llama3.2:1b-instruct-q4_K_M"
        ),
        "judge_model": "qwen2.5:1.5b",
        "embedding_model": (
            "BAAI/bge-small-en-v1.5"
        ),
        "reranker_model": (
            "cross-encoder/"
            "ms-marco-MiniLM-L4-v2"
        ),
        "retrieved_chunks": 10,
        "chunk_size": 1000,
        "chunk_overlap": 150,
    },
)


print("\nEvaluation finished.")
print("Results folder:", results_folder)